"""Corrected EK1D copper tutorial, version 2.1.0.

theta dc_i/dt = -div(J_i) + theta R_i, with pore-water c in mol/m3,
J_i = -Dstar_i grad(c_i) + z_i F/(RT) Dstar_i E c_i, and
Dstar_i = theta D0_i/tau. All fluxes are per bulk cross-sectional area.

The saturated, hydraulically closed column has q_total=0. Its induced
hydraulic counterflow cancels EOF (q_h=-k_eo E); pressure magnitude is not
calculated because hydraulic permeability is not specified. Cu, Na and NO3
cannot cross the endpoints. Ideal Faradaic H/OH injection uses the SAME
uniform ionic current as the interior fluxes. Endpoint solution potentials
are 20 and 0 V; electrode overpotentials, gas, heat and activity corrections
are omitted. This is an illustrative redistribution model, not a Cu recovery
experiment or an independently validated remediation prediction.

Current continuity is solved exactly for the piecewise-linear upwind face
law, including reversed local fields and diffusion current. Transport is
explicit conservative finite volume with simultaneous water, sorption and
reversible precipitation equilibrium. SSPRK2 reconstructs equilibrium after
each forward transport stage and the final component mixture. The combined
outgoing-coefficient CFL includes theta. No concentrations are
clipped and no ion is adjusted to repair charge during time integration.

Article case: python reproduce.py --case N400_cfl01 --output rerun_selected --backend native
Run commands, companion modules and reference-data instructions are in README.md.
The article figures are generated by plot_article_figures.py; save() also writes
separate per-run diagnostic plots.
"""
